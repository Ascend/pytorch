def _choose_group_m(num_blocks_m: int) -> int:
    """Choose GROUP_M as the largest factor of num_blocks_m not exceeding 8.

    This guarantees num_blocks_m % GROUP_M == 0, so the super-grouping
    tile assignment never needs runtime % runtime (which hangs the NPU
    Triton backend).  Falls back to 1 if no larger factor exists.
    """
    for g in [8, 4, 2, 1]:
        if num_blocks_m % g == 0:
            return g
    return 1


def _get_npu_persistent_mm_configs(
    m: int,
    n: int,
    k: int,
) -> List[Dict[str, Any]]:
    """Generate tiling configs for the NPU persistent triton matmul template.

    Each config includes NUM_BLOCKS_M, NUM_BLOCKS_N, NUM_BLOCKS, GROUP_M,
    WIDTH, NUM_SMS and NUM_TILES_PER_PROGRAM which are required by the
    persistent + super-grouping kernel strategy.

    Key invariants:
      * GROUP_M is always a factor of NUM_BLOCKS_M, so all modulo /
        integer-division operations in the template are
        (runtime value) % (compile-time constant) — safe for the NPU backend.
      * NUM_SMS and NUM_TILES_PER_PROGRAM are compile-time constants
        (required for the outer loop bound).

    .. note::
        The persistent kernel bakes ``NUM_BLOCKS``, ``NUM_TILES_PER_PROGRAM``,
        ``WIDTH``, ``NUM_BLOCKS_M`` and ``NUM_BLOCKS_N`` into the kernel as
        ``tl.constexpr``.  These **must** match the actual runtime shape:

        * ``NUM_BLOCKS`` too small → output tiles missed → **wrong results**
        * ``NUM_TILES_PER_PROGRAM`` too small → tiles not covered →
          **wrong results**
        * ``WIDTH`` / ``GROUP_M`` derived from wrong ``NUM_BLOCKS_N`` →
          tiles mapped to wrong ``(pid_m, pid_n)`` → **wrong results**

        For dynamic (symbolic) shapes we cannot guarantee these compile-time
        constants match the runtime shape, so the persistent template is
        **skipped** and the non-persistent template (which computes the grid
        at runtime) is used instead.
    """
    # --- Dynamic-shape guard ---
    # If any of M, N, K is symbolic, we cannot safely determine the
    # compile-time tile constants.  Return an empty config list so that
    # no persistent-mm choices are added; the non-persistent template
    # (npu_triton_mm_template) will still be available.
    if _is_symbolic_dim(m) or _is_symbolic_dim(n) or _is_symbolic_dim(k):
        log.debug(
            "NPU persistent mm: skipping for dynamic shape "
            "(m=%s, n=%s, k=%s) — compile-time tile constants "
            "cannot be safely determined for symbolic dimensions; "
            "falling back to non-persistent triton mm template.",
            m, n, k,
        )
        return []

    configs: List[Dict[str, Any]] = []

    # Dynamically generate tile combos based on the actual shape
    # (same generator as the non-persistent template, so both templates
    # cover the same padding-eliminating BLOCK_M values).
    tile_combos = _gen_tile_combos(m, n, k, max_block_dim=256)

    for block_m, block_n, block_k in tile_combos:
        num_blocks_m = (m + block_m - 1) // block_m
        num_blocks_n = (n + block_n - 1) // block_n
        num_blocks = num_blocks_m * num_blocks_n

        # Skip if the tile is larger than the matrix (no benefit).
        if num_blocks == 0:
            continue

        # Choose GROUP_M as a factor of num_blocks_m (≤ 8) so that
        # group_size == GROUP_M always holds (no partial last group).
        group_m = _choose_group_m(num_blocks_m)
        width = group_m * num_blocks_n
        even_k = (k % block_k == 0)

        # Choose 2 core counts based on num_blocks (instead of the
        # previous fixed [8, 16, 32, 56]) — this significantly reduces
        # the number of configs while still covering the useful
        # parallelism range.
        if num_blocks >= 56:
            core_options = [56, 32]
        elif num_blocks >= 32:
            core_options = [32, 16]
        elif num_blocks >= 16:
            core_options = [16, 8]
        else:
            core_options = [max(num_blocks, 8)]

        # num_stages based on K-loop iterations.
        k_iters = (k + block_k - 1) // block_k
        stages_list = _select_num_stages(k_iters, block_k)

        for num_cores in core_options:
            # Don't launch more programs than there are blocks
            actual_num_cores = min(num_cores, num_blocks)
            if actual_num_cores == 0:
                continue
            # Compute tiles per program (compile-time constant for loop bound)
            num_tiles_per_program = (num_blocks + actual_num_cores - 1) // actual_num_cores
            for num_stages in stages_list:
                configs.append({
                    "BLOCK_M": block_m,
                    "BLOCK_N": block_n,
                    "BLOCK_K": block_k,
                    "GROUP_M": group_m,
                    "NUM_BLOCKS_M": num_blocks_m,
                    "NUM_BLOCKS_N": num_blocks_n,
                    "NUM_BLOCKS": num_blocks,
                    "WIDTH": width,
                    "NUM_SMS": actual_num_cores,
                    "NUM_TILES_PER_PROGRAM": num_tiles_per_program,
                    "num_stages": num_stages,
                    "num_warps": 4,
                    "ALLOW_TF32": "False",
                    "ACC_TYPE": "tl.float32",
                    "EVEN_K": even_k,
                })

    return configs


