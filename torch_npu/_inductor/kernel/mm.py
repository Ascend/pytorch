def add_npu_triton_addmm_choices(
    choices: List[ir.ChoiceCaller],
    layout: "ir.Layout",
    inp: "ir.IRNode",
    mat1: "ir.IRNode",
    mat2: "ir.IRNode",
    m: int,
    n: int,
    k: int,
    alpha: float = 1,
    beta: float = 1,
) -> None:
    """Add NPU Triton addmm template choices to the choices list.

    Reuses the same ``npu_triton_mm_template`` (triton_mm.py.jinja) as plain
    ``mm``.  The bias term is fused into the kernel epilogue via the
    ``prefix_args`` + ``epilogue_fn`` mechanism:

      * ``input_nodes = [inp, mat1, mat2]`` — bias (``inp``) is placed first so
        it becomes a *prefix arg*: it is NOT named in ``{{def_kernel("A", "B")}}``
        but is automatically loaded inside ``{{store_output}}`` and passed to
        ``epilogue_fn``.
      * ``prefix_args=1`` tells the codegen that the first input node is the
        bias/epilogue input (not a matmul operand).
      * ``epilogue_fn=addmm_epilogue(dtype, alpha, beta)`` generates
        ``beta * bias + alpha * acc`` at store time, fusing the addmm bias
        addition into the matmul kernel's epilogue.

    This mirrors how the community ``tuned_addmm`` reuses ``mm_template`` with
    ``prefix_args=1`` and ``addmm_epilogue``.
    """
    # bias first (prefix arg), then the two matmul operands named A, B in jinja
    input_nodes = [inp, mat1, mat2]
    # Derive tiling-relevant attributes from the IR nodes.
    try:
        dtype = layout.dtype
        is_a_trans = _is_col_major(mat1.get_size(), mat1.get_stride())
        is_b_trans = _is_col_major(mat2.get_size(), mat2.get_stride())
    except Exception:
        dtype = None
        is_a_trans = False
        is_b_trans = False
    # Use max_block_dim=128 for addmm: the bias epilogue fusion (loading
    # and broadcasting the bias vector) adds register pressure, so 256-dim
    # tiles can cause "cc overflow" on the NPU.
    configs = _get_npu_mm_configs(
        m, n, k, max_block_dim=256,
        dtype=dtype, is_a_trans=is_a_trans, is_b_trans=is_b_trans, has_bias=True,
    )

    # Build the epilogue function that fuses beta*bias + alpha*acc.
    epilogue_fn = addmm_epilogue(layout.dtype, alpha, beta)

    for cfg in configs:
        # Extract kernel launch params (not passed as constexpr defines)
        num_stages = cfg.pop("num_stages")
        num_warps = cfg.pop("num_warps")

        try:
            choice = npu_triton_mm_template.generate(
                input_nodes=input_nodes,
                layout=layout,
                num_stages=num_stages,
                num_warps=num_warps,
                prefix_args=1,
                epilogue_fn=epilogue_fn,
                **cfg,
            )
            if choice is not None:
                choices.append(choice)
        except Exception:
            log.debug(
                "Failed to generate NPU triton addmm choice with config %s",
                cfg,
                exc_info=True,
            )


def is_contiguous_striding(size, stride) -> bool:
    def is_contiguous_row_major(stride, size) -> bool:
        # to support non-contiguous row-major input
        return V.graph.sizevars.statically_known_equals(stride[1], 1) and \
            V.graph.sizevars.statically_known_equals(stride[0], size[1])

    def is_contiguous_col_major(stride, size) -> bool:
        # to support non-contiguous col-major input
        return V.graph.sizevars.statically_known_equals(stride[0], 1) and \
            V.graph.sizevars.statically_known_equals(stride[1], size[0])

    return (
        is_contiguous_row_major(stride, size)
        or is_contiguous_col_major(stride, size)
    )


def _is_col_major(size, stride) -> bool:
    """Check if a 2D tensor is stored in column-major (transposed) layout.

    Returns True when stride[0]==1 and stride[1]==size[0], meaning the
    first dimension is the inner (contiguous) dimension — i.e. the tensor
    is the transpose of a row-major matrix.
    """
    try:
        return (
            V.graph.sizevars.statically_known_equals(stride[0], 1)
            and V.graph.sizevars.statically_known_equals(stride[1], size[0])
        )
    except Exception:
        return False


def _register_npu_inductor_mm():
    @register_lowering(aten.mm, type_promotion_kind=None)
    def tuned_mm(mat1, mat2, *, layout=None):

        m, n, k, layout, mat1, mat2 = mm_args(mat1, mat2, layout=layout)
        name = "mm"

        aten_layout = layout
        if not inductor_config.max_autotune:
            aten_layout = FlexibleLayout(
                device=layout.device, dtype=layout.dtype, size=layout.size
            )

        # options to tune from
        choices = (
            [aten_mm.bind((mat1, mat2), aten_layout)] if use_aten_gemm_kernels() else []
        )
        _, is_nonzero = _is_static_problem(layout)

        is_contiguous_input = (
            is_contiguous_striding(mat1.get_size(), mat1.get_stride())
            and is_contiguous_striding(mat2.get_size(), mat2.get_stride())
        )
        if (
            is_contiguous_input
            and is_nonzero
            and use_catlass_template("mm", layout, m, n, k)
        ):
            CATLASS1xGemmTemplate.add_catlass_gemm_choices(
                choices, layout, [mat1, mat2]
            )
            # debug log
            log.info("Choices number after catlass template: %s", len(choices))

        if is_nonzero and use_ck_gemm_template(layout, m, n, k):
            CKGemmTemplate.add_ck_gemm_choices(choices, layout, [mat1, mat2])

        if use_cpp_gemm_template(layout, mat1, mat2):
            CppGemmTemplate.add_choices(
                choices,
                layout,
                [mat1, mat2],
            )

        # Add NPU Triton matmul template choices for CV (Compute/Vector) fusion.
        # The triton template supports epilogue fusion: when the matmul output
        # is consumed by pointwise ops (e.g. add, relu), the scheduler fuses
        # them into the kernel's epilogue via {{store_output}}.
        if is_nonzero and use_triton_template(layout):
            try:
                add_npu_triton_mm_choices(
                    choices, layout, mat1, mat2, m, n, k
                )
                log.debug(
                    "NPU Triton CV fusion: added triton mm template choices "
                    "for mm(%d, %d, %d), total choices now %d",
                    m,
                    n,
                    k,
                    len(choices),
                )
            except Exception:
                log.warning("Failed to add NPU triton mm template choices", exc_info=True)

        # Add NPU persistent Triton matmul template choices.
        # Uses new_triton_mm.py.jinja with a persistent kernel strategy:
        # each program serially processes multiple output tiles, improving
        # L2 cache reuse via super-grouping and reducing launch overhead.
        # Best for large matrices where num_tiles >> num_cores.
        # Also supports epilogue fusion via {{store_output}}.
        if is_nonzero and use_triton_template(layout):
            try:
                add_npu_persistent_mm_choices(
                    choices, layout, mat1, mat2, m, n, k
                )
                log.debug(
                    "NPU persistent mm: added persistent mm template choices "
                    "for mm(%d, %d, %d), total choices now %d",
                    m,
                    n,
                    k,
                    len(choices),
                )
            except Exception:
                log.warning("Failed to add NPU persistent mm template choices", exc_info=True)

        # Add NPU resident-B Triton matmul template choices.
        # When N*K fits in L0B, this template loads B once and streams over
        # M-tiles, eliminating redundant B reloads.  Best for M>>N, small N*K.
        if is_nonzero and use_triton_template(layout):
            try:
                add_npu_resident_b_mm_choices(
                    choices, layout, mat1, mat2, m, n, k
                )
                log.debug(
                    "NPU resident-B mm: added choices "
                    "for mm(%d, %d, %d), total choices now %d",
                    m, n, k, len(choices),
                )
            except Exception:
                log.warning("Failed to add NPU resident-B mm template choices", exc_info=True)

        # Add NPU resident-A Triton matmul template choices.
        # When M*K fits in L0A, this template loads A once and streams over
        # N-tiles, eliminating redundant A reloads.  Best for N>>M, small M*K.
        if is_nonzero and use_triton_template(layout):
            try:
                add_npu_resident_a_mm_choices(
                    choices, layout, mat1, mat2, m, n, k
                )
                log.debug(
                    "NPU resident-A mm: added choices "
                    "for mm(%d, %d, %d), total choices now %d",
                    m, n, k, len(choices),
                )
            except Exception:
                log.warning("Failed to add NPU resident-A mm template choices", exc_info=True)

        input_nodes = [mat1, mat2]

        if (
            len(choices) == 0
            and not use_aten_gemm_kernels()
            and inductor_config.autotune_fallback_to_aten
        ):
            log.warning("No choices for GEMM, using ATen backend as fallback")
            return aten_mm.bind((mat1, mat2), aten_layout).output_node()

        for k in inductor_config.external_matmul:
            choices.append(lazy_register_extern_choice(k).bind((mat1, mat2), layout))

        try:
            node, _ = autotune_select_algorithm(
                name, choices, [mat1, mat2], layout
            )
            return node
        except NoValidChoicesError:
            if not inductor_config.autotune_fallback_to_aten:
                raise
            log.warning(
                "All choices for GEMM were invalid, using ATen backend as fallback"
            )
            return aten_mm.bind((mat1, mat2), aten_layout).output_node()


def _register_npu_inductor_addmm():

    def addmm_args(
        mat1,
        mat2,
        inp,
        *others,
        layout=None,
        out_dtype=None,
        use_4x2_dim=False,
        mat2_transposed=False,
    ):
        """
        Common arg processing for mm,bmm,addmm,etc
        """
        mat1, mat2, inp = realize_inputs(mat1, mat2, inp)
        *b1, m, k1 = mat1.get_size()
        if mat2_transposed:
            *b2, n, k2 = mat2.get_size()
        else:
            *b2, k2, n = mat2.get_size()
        b = [V.graph.sizevars.check_equals_and_simplify(a, b) for a, b in zip(b1, b2)]
        if use_4x2_dim:
            k2 = k2 * 2
        k = V.graph.sizevars.check_equals_and_simplify(k1, k2)
        if layout is None:
            from torch._inductor.ir import FixedLayout

            if out_dtype is None:
                out_dtype = mat1.get_dtype()

            layout = FixedLayout(
                mat1.get_device(),
                out_dtype,
                [*b, m, n],
            )
        else:
            if out_dtype is not None:
                raise ValueError("out_dtype is ignored if layout is specified.")

        others = [realize_inputs(expand(x, layout.size)) for x in others]
        return [m, n, k, layout, mat1, mat2, inp, *others]


    @register_lowering(aten.addmm, type_promotion_kind=None)
    def tuned_addmm(inp, mat1, mat2, *, alpha=1, beta=1, layout=None):

        # Fallback addmm using fallback handler before mm_args(), if there is no valid catlass template.
        # In case, aten_addmm.bind would decompose addmm to broadcast + mm + add.
        shape1 = mat1.shape
        shape2 = mat2.shape
        bias_shape = inp.shape
        m0 = shape1[0]
        k0 = shape1[1]
        n0 = shape2[1]

        if layout is None:

            layout_tmp = FixedLayout(
                mat1.get_device(),
                mat1.get_dtype(),
                [m0, n0],
            )

        static_shape_tmp, is_nonzero_tmp = _is_static_problem(layout_tmp if layout is None else layout)

        if not (static_shape_tmp and is_nonzero_tmp):
            return fallback_handler(aten.addmm.default)(inp, mat1, mat2, alpha=alpha, beta=beta)

        try:
            is_contiguous_input_tmp = (
                is_contiguous_striding(mat1.get_size(), mat1.get_stride())
                and is_contiguous_striding(mat2.get_size(), mat2.get_stride())
            )
        except NotImplementedError:
            is_contiguous_input_tmp = False

        # Determine whether the catlass template is available for this problem.
        # We no longer fall back immediately when catlass is unavailable: the
        # NPU Triton addmm template (reusing npu_triton_mm_template with
        # prefix_args=1 + addmm_epilogue) can still be tried below.
        catlass_available = (
            is_contiguous_input_tmp
            and use_catlass_template("addmm", layout_tmp if layout is None else layout, m0, n0, k0)
        )
        # Determine whether the NPU Triton template is available.
        triton_available = is_contiguous_input_tmp and use_triton_template(
            layout_tmp if layout is None else layout
        )
        *b2, k2, n = mat2.get_size()
        # When N == 1, fall back to ATen addmm even when a triton template is
        # available, because the Triton addmm template cannot safely handle
        # N == 1 without modifying the template itself.
        #
        # Background — why N == 1 is incompatible with the Triton addmm template:
        #   bias (N,)  --expand-->  (M, N)  --realize_inputs-->  buf0
        #              stride (1,)          stride (0, 1)
        # When N == 1, expand produces a (M, 1) tensor whose M-dim stride is 0
        # (broadcast).  The bias source has a single element (bias[0]), so
        # every position in the (M, 1) tensor holds the same scalar value.
        #
        # During the pre-codegen buffer-elimination pass, the upstream scheduler
        # inspects buf0 and finds:
        #   1. Its data source is a ReinterpretView with stride 0.
        #   2. make_loader() can inline buf0's content — it returns
        #      ops.load("bias_src", [0]) directly, bypassing buf0 entirely.
        #   3. Since buf0 is never actually tl.load-ed (its content is inlined
        #      into consumer expressions), the scheduler adds buf0 to
        #      V.graph.removed_buffers — no buffer allocation, no kernel arg.
        #
        # Conflict: the Triton addmm template's {{store_output}} still loads the
        # bias by buffer name via input_node.make_loader() -> ops.load(self.name),
        # which trips `assert name not in V.graph.removed_buffers`.
        #
        # Additionally, the template's B load has no N-dimensional mask, so when
        # N < BLOCK_N (minimum 16) it would access out-of-bounds columns of B.
        #
        # When N >= 2, buf0's source has N distinct elements, so make_loader()
        # cannot inline it into a single scalar expression — the scheduler
        # keeps buf0 and no assertion is triggered.
        #
        # Fixing this requires either modifying the template (adding an
        # N-dimensional mask to B's load) or forcing the bias to realize()
        # into a real Buffer.  Both approaches are intentionally avoided
        # here to keep the template untouched and the change minimal;
        # N == 1 simply falls back to the ATen addmm implementation.
        # If neither catlass nor triton templates are available, fall back.
        if (not (catlass_available or triton_available)) or n == 1:
            return fallback_handler(aten.addmm.default)(inp, mat1, mat2, alpha=alpha, beta=beta)

        ordered_kwargs_for_cpp_kernel = ("beta", "alpha")
        m, n, k, layout, mat1, mat2, inp_origin, inp_expanded = addmm_args(
            mat1, mat2, inp, inp, layout=layout
        )
        static_shape, is_nonzero = _is_static_problem(layout)
        if (not is_nonzero) or (not inductor_config.max_autotune):
            if isinstance(layout, FixedLayout):
                layout = FlexibleLayout(
                    device=layout.device, dtype=layout.dtype, size=layout.size
                )
            choices = (
                [
                    aten_addmm.bind(
                        (inp, mat1, mat2),
                        layout,
                        alpha=alpha,
                        beta=beta,
                    )
                ]
                if use_aten_gemm_kernels()
                else []
            )
            node, _ = autotune_select_algorithm(
                "addmm", choices, [inp, mat1, mat2], layout
            )
            return node

        choices = (
            [
                aten_addmm.bind(
                    (inp_origin, mat1, mat2),
                    layout,
                    alpha=alpha,
                    beta=beta,
                )
            ]
            if use_aten_gemm_kernels()
            else []
        )

        is_contiguous_input = (
            is_contiguous_striding(mat1.get_size(), mat1.get_stride())
            and is_contiguous_striding(mat2.get_size(), mat2.get_stride())
        )
        if (
            is_contiguous_input
            and static_shape
            and is_nonzero
            and use_catlass_template("addmm", layout, m, n, k)
        ):
            # Filter out broadcasting on the last dim of the bias term
            # since catlass does not support it yet.
            if (
                PythonWrapperCodegen.statically_known_int_or_none(
                    inp_expanded.layout.stride[-1]
                )
                != 0
            ):
                CATLASS1xGemmTemplate.add_catlass_gemm_choices(
                    choices,
                    layout,
                    [mat1, mat2, inp_expanded],
                    alpha=alpha,
                    beta=beta,
                )

        if is_nonzero and use_ck_gemm_template(layout, m, n, k):
            CKGemmTemplate.add_ck_gemm_choices(
                choices,
                layout,
                [mat1, mat2, inp_expanded],
                alpha=alpha,
                beta=beta,
            )

        if use_cpp_gemm_template(layout, mat1, mat2):
            CppGemmTemplate.add_choices(
                choices,
                layout,
                [inp_expanded, mat1, mat2],
                alpha=alpha,
                beta=beta,
                has_bias=True,
            )

        # Add NPU Triton addmm template choices.
        # Reuses npu_triton_mm_template (triton_mm.py.jinja) with the bias
        # fused into the epilogue via prefix_args=1 + addmm_epilogue.
        # This enables the autotuner to try a Triton kernel for addmm and
        # also supports CV epilogue fusion (e.g. downstream pointwise ops
        # fused into {{store_output}}).
        if is_nonzero and use_triton_template(layout):
            try:
                add_npu_triton_addmm_choices(
                    choices,
                    layout,
                    inp_expanded,
                    mat1,
                    mat2,
                    m,
                    n,
                    k,
                    alpha=alpha,
                    beta=beta,
                )
                log.debug(
                    "NPU Triton CV fusion: added triton addmm template choices "
                    "for addmm(%d, %d, %d), total choices now %d",
                    m,
                    n,
                    k,
                    len(choices),
                )
            except Exception:
                log.warning("Failed to add NPU triton addmm template choices", exc_info=True)

        # Add NPU persistent Triton addmm template choices.
        # Reuses npu_persistent_mm_template with prefix_args=1 + addmm_epilogue,
        # enabling the persistent kernel strategy (serial tile processing
        # with super-grouping) for addmm with bias fused into the epilogue.
        if is_nonzero and use_triton_template(layout):
            try:
                add_npu_persistent_addmm_choices(
                    choices,
                    layout,
                    inp_expanded,
                    mat1,
                    mat2,
                    m,
                    n,
                    k,
                    alpha=alpha,
                    beta=beta,
                )
                log.debug(
                    "NPU persistent addmm: added persistent addmm template choices "
                    "for addmm(%d, %d, %d), total choices now %d",
                    m,
                    n,
                    k,
                    len(choices),
                )
            except Exception:
                log.warning("Failed to add NPU persistent addmm template choices", exc_info=True)

        # Add NPU resident-B Triton addmm template choices.
        # Same resident-B strategy (full-load B, streaming M) but with the
        # addmm bias fused into the epilogue via prefix_args=1.
        if is_nonzero and use_triton_template(layout):
            try:
                add_npu_resident_b_addmm_choices(
                    choices,
                    layout,
                    inp_expanded,
                    mat1,
                    mat2,
                    m,
                    n,
                    k,
                    alpha=alpha,
                    beta=beta,
                )
                log.debug(
                    "NPU resident-B addmm: added choices "
                    "for addmm(%d, %d, %d), total choices now %d",
                    m, n, k, len(choices),
                )
            except Exception:
                log.warning("Failed to add NPU resident-B addmm template choices", exc_info=True)

        # Add NPU resident-A Triton addmm template choices.
        # Same resident-A strategy (full-load A, streaming N) but with the
        # addmm bias fused into the epilogue via prefix_args=1.
        if is_nonzero and use_triton_template(layout):
            try:
                add_npu_resident_a_addmm_choices(
                    choices,
                    layout,
                    inp_expanded,
                    mat1,
                    mat2,
                    m,
                    n,
                    k,
                    alpha=alpha,
                    beta=beta,
                )
                log.debug(
                    "NPU resident-A addmm: added choices "
                    "for addmm(%d, %d, %d), total choices now %d",
                    m, n, k, len(choices),
                )
            except Exception:
                log.warning("Failed to add NPU resident-A addmm template choices", exc_info=True)

        add_aten_fallback = False
        if len(choices) == 0:
            log.warning("No choices for GEMM, using ATen backend as fallback")
            add_aten_fallback = True

        if add_aten_fallback:
            choices.append(
                aten_addmm.bind(
                    (inp_origin, mat1, mat2),
                    layout,
                    ordered_kwargs_for_cpp_kernel,
                    alpha=alpha,
                    beta=beta,
                )
            )

        try:
            node, _ = autotune_select_algorithm(
                "addmm", choices, [inp_origin, mat1, mat2], layout
            )
            return node
        except NoValidChoicesError:
            if not inductor_config.autotune_fallback_to_aten:
                raise
            log.warning(
                "All choices for GEMM were invalid, using ATen backend as fallback"
            )
            fallback_choice = aten_addmm.bind(
                (inp, mat1, mat2),
                layout,
                ordered_kwargs_for_cpp_kernel,
                alpha=alpha,
                beta=beta,
            )
            return fallback_choice.output_node()
