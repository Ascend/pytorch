def add_npu_triton_addmm_choices(
    choices: List[ir.ChoiceCaller],
    layout: "ir.Layout",
    inp: "ir.IRNode",
    mat1: "ir.IRNode",
    mat2: "ir.IRNode",
    m: int,
    n: int,
    k: int,
    alpha: float = 1,
    beta: float = 1,
) -> None:
    """Add NPU Triton addmm template choices to the choices list.

    Reuses the same ``npu_triton_mm_template`` (triton_mm.py.jinja) as plain
    ``mm``.  The bias term is fused into the kernel epilogue via the
    ``prefix_args`` + ``epilogue_fn`` mechanism:

      * ``input_nodes = [inp, mat1, mat2]`` — bias (``inp``) is placed first so
        it becomes a *prefix arg*: it is NOT named in ``{{def_kernel("A", "B")}}``
        but is automatically loaded inside ``{{store_output}}`` and passed to
        ``epilogue_fn``.
      * ``prefix_args=1`` tells the codegen that the first input node is the
        bias/epilogue input (not a matmul operand).
      * ``epilogue_fn=addmm_epilogue(dtype, alpha, beta)`` generates
        ``beta * bias + alpha * acc`` at store time, fusing the addmm bias
        addition into the matmul kernel's epilogue.

    This mirrors how the community ``tuned_addmm`` reuses ``mm_template`` with
    ``prefix_args=1`` and ``addmm_epilogue``.
    """
    # bias first (prefix arg), then the two matmul operands named A, B in jinja
    input_nodes = [inp, mat1, mat2]
    # Use max_block_dim=128 for addmm: the bias epilogue fusion (loading
    # and broadcasting the bias vector) adds register pressure, so 256-dim
    # tiles can cause "cc overflow" on the NPU.
    configs = _get_npu_mm_configs(m, n, k, max_block_dim=128)

    # Build the epilogue function that fuses beta*bias + alpha*acc.
    epilogue_fn = addmm_epilogue(layout.dtype, alpha, beta)

    for cfg in configs:
        # Extract kernel launch params (not passed as constexpr defines)
        num_stages = cfg.pop("num_stages")
        num_warps = cfg.pop("num_warps")

        try:
            choice = npu_triton_mm_template.generate(
                input_nodes=input_nodes,
                layout=layout,
                num_stages=num_stages,
                num_warps=num_warps,
                prefix_args=1,
                epilogue_fn=epilogue_fn,
                **cfg,
            )
            if choice is not None:
                choices.append(choice)
        except Exception as e:
            log.debug(
                "Failed to generate NPU triton addmm choice with config %s: %s",
                cfg,
                e,
            )


def is_contiguous_striding(size, stride) -> bool:
    def is_contiguous_row_major(stride, size) -> bool:
        # to support non-contiguous row-major input
        return V.graph.sizevars.statically_known_equals(stride[1], 1) and \
               V.graph.sizevars.statically_known_equals(stride[0], size[1])

    def is_contiguous_col_major(stride, size) -> bool:
        # to support non-contiguous col-major input
        return V.graph.sizevars.statically_known_equals(stride[0], 1) and \
               V.graph.sizevars.statically_known_equals(stride[1], size[0])

    return (
        is_contiguous_row_major(stride, size)
        or is_contiguous_col_major(stride, size)
    )


def _register_npu_inductor_mm():
    @register_lowering(aten.mm, type_promotion_kind=None)
    def tuned_mm(mat1, mat2, *, layout=None):

        m, n, k, layout, mat1, mat2 = mm_args(mat1, mat2, layout=layout)
        name = "mm"

        aten_layout = layout
        if not inductor_config.max_autotune:
            aten_layout = FlexibleLayout(
                device=layout.device, dtype=layout.dtype, size=layout.size
            )

        # options to tune from
        choices = (
            [aten_mm.bind((mat1, mat2), aten_layout)] if use_aten_gemm_kernels() else []
        )
        _, is_nonzero = _is_static_problem(layout)

        is_contiguous_input = (
            is_contiguous_striding(mat1.get_size(), mat1.get_stride())
            and is_contiguous_striding(mat2.get_size(), mat2.get_stride())
        )
        if (
            is_contiguous_input
            and is_nonzero
            and use_catlass_template("mm", layout, m, n, k)
        ):
            CATLASS1xGemmTemplate.add_catlass_gemm_choices(
                choices, layout, [mat1, mat2]
            )
            # debug log
            log.info(f"Choices number after catlass template: {len(choices)}")

        if is_nonzero and use_ck_gemm_template(layout, m, n, k):
            CKGemmTemplate.add_ck_gemm_choices(choices, layout, [mat1, mat2])

        if use_cpp_gemm_template(layout, mat1, mat2):
            CppGemmTemplate.add_choices(
                choices,
                layout,
                [mat1, mat2],
            )

        # Add NPU Triton matmul template choices for CV (Compute/Vector) fusion.
        # The triton template supports epilogue fusion: when the matmul output
        # is consumed by pointwise ops (e.g. add, relu), the scheduler fuses
        # them into the kernel's epilogue via {{store_output}}.
        if is_nonzero and use_triton_template(layout):
            try:
                add_npu_triton_mm_choices(
                    choices, layout, mat1, mat2, m, n, k
                )
                log.debug(
                    "NPU Triton CV fusion: added triton mm template choices "
                    "for mm(%d, %d, %d), total choices now %d",
                    m,
                    n,
                    k,
                    len(choices),
                )
            except Exception as e:
                log.warning("Failed to add NPU triton mm template choices: %s", e)

        # Add NPU persistent Triton matmul template choices.
        # Uses new_triton_mm.py.jinja with a persistent kernel strategy:
        # each program serially processes multiple output tiles, improving
        # L2 cache reuse via super-grouping and reducing launch overhead.
        # Best for large matrices where num_tiles >> num_cores.
        # Also supports epilogue fusion via {{store_output}}.
        if is_nonzero and use_triton_template(layout):
            try:
                add_npu_persistent_mm_choices(
                    choices, layout, mat1, mat2, m, n, k
                )
                log.debug(
                    "NPU persistent mm: added persistent mm template choices "
                    "for mm(%d, %d, %d), total choices now %d",
                    m,
                    n,
                    k,
                    len(choices),
                )
            except Exception as e:
                log.warning("Failed to add NPU persistent mm template choices: %s", e)

        input_nodes = [mat1, mat2]

        if (
            len(choices) == 0
            and not use_aten_gemm_kernels()
            and inductor_config.autotune_fallback_to_aten
        ):
            log.warning("No choices for GEMM, using ATen backend as fallback")
            return aten_mm.bind((mat1, mat2), aten_layout).output_node()

        for k in inductor_config.external_matmul:
            choices.append(lazy_register_extern_choice(k).bind((mat1, mat2), layout))

        try:
            return autotune_select_algorithm(name, choices, [mat1, mat2], layout)
        except NoValidChoicesError:
            if not inductor_config.autotune_fallback_to_aten:
                raise
            log.warning(
                "All choices for GEMM were invalid, using ATen backend as fallback"
            )
            return aten_mm.bind((mat1, mat2), aten_layout).output_node()


def _register_npu_inductor_addmm():
    @register_lowering(aten.addmm, type_promotion_kind=None)
    def tuned_addmm(inp, mat1, mat2, *, alpha=1, beta=1, layout=None):

        # Fallback addmm using fallback handler before mm_args(), if there is no valid catlass template.
        # In case, aten_addmm.bind would decompose addmm to broadcast + mm + add.
        shape1 = mat1.shape
        shape2 = mat2.shape
        bias_shape = inp.shape
        m0 = shape1[0]
        k0 = shape1[1]
        n0 = shape2[1]

        if layout is None:
            from torch._inductor.ir import FixedLayout

            layout_tmp = FixedLayout(
                mat1.get_device(),
                mat1.get_dtype(),
                [m0, n0],
            )

        static_shape_tmp, is_nonzero_tmp = _is_static_problem(layout_tmp if layout is None else layout)

        if not (static_shape_tmp and is_nonzero_tmp):
            return fallback_handler(aten.addmm.default)(inp, mat1, mat2, alpha=alpha, beta=beta)

        try:
            is_contiguous_input_tmp = (
                is_contiguous_striding(mat1.get_size(), mat1.get_stride())
                and is_contiguous_striding(mat2.get_size(), mat2.get_stride())
            )
        except NotImplementedError:
            is_contiguous_input_tmp = False

        # Determine whether the catlass template is available for this problem.
        # We no longer fall back immediately when catlass is unavailable: the
        # NPU Triton addmm template (reusing npu_triton_mm_template with
        # prefix_args=1 + addmm_epilogue) can still be tried below.
        catlass_available = (
            is_contiguous_input_tmp
            and use_catlass_template("addmm", layout_tmp if layout is None else layout, m0, n0, k0)
        )
        # Determine whether the NPU Triton template is available.
        triton_available = is_contiguous_input_tmp and use_triton_template(
            layout_tmp if layout is None else layout
        )

        # If neither catlass nor triton templates are available, fall back.
        if not (catlass_available or triton_available):
            return fallback_handler(aten.addmm.default)(inp, mat1, mat2, alpha=alpha, beta=beta)

        ordered_kwargs_for_cpp_kernel = ("beta", "alpha")
        m, n, k, layout, mat1, mat2, inp_expanded = mm_args(
            mat1, mat2, inp, layout=layout
        )
        static_shape, is_nonzero = _is_static_problem(layout)
        if (not is_nonzero) or (not inductor_config.max_autotune):
            if isinstance(layout, FixedLayout):
                layout = FlexibleLayout(
                    device=layout.device, dtype=layout.dtype, size=layout.size
                )
            choices = (
                [
                    aten_addmm.bind(
                        (inp, mat1, mat2),
                        layout,
                        alpha=alpha,
                        beta=beta,
                    )
                ]
                if use_aten_gemm_kernels()
                else []
            )
            return autotune_select_algorithm(
                "addmm", choices, [inp, mat1, mat2], layout
            )

        choices = (
            [
                aten_addmm.bind(
                    (inp_expanded, mat1, mat2),
                    layout,
                    alpha=alpha,
                    beta=beta,
                )
            ]
            if use_aten_gemm_kernels()
            else []
        )

        is_contiguous_input = (
            is_contiguous_striding(mat1.get_size(), mat1.get_stride())
            and is_contiguous_striding(mat2.get_size(), mat2.get_stride())
        )
        if (
            is_contiguous_input
            and static_shape
            and is_nonzero
            and use_catlass_template("addmm", layout, m, n, k)
        ):
            # Filter out broadcasting on the last dim of the bias term
            # since catlass does not support it yet.
            if (
                PythonWrapperCodegen.statically_known_int_or_none(
                    inp_expanded.layout.stride[-1]
                )
                != 0
            ):
                CATLASS1xGemmTemplate.add_catlass_gemm_choices(
                    choices,
                    layout,
                    [mat1, mat2, inp_expanded],
                    alpha=alpha,
                    beta=beta,
                )

        if is_nonzero and use_ck_gemm_template(layout, m, n, k):
            CKGemmTemplate.add_ck_gemm_choices(
                choices,
                layout,
                [mat1, mat2, inp_expanded],
                alpha=alpha,
                beta=beta,
            )

        if use_cpp_gemm_template(layout, mat1, mat2):
            CppGemmTemplate.add_choices(
                choices,
                layout,
                [inp_expanded, mat1, mat2],
                alpha=alpha,
                beta=beta,
                has_bias=True,
            )

        # Add NPU Triton addmm template choices.
        # Reuses npu_triton_mm_template (triton_mm.py.jinja) with the bias
        # fused into the epilogue via prefix_args=1 + addmm_epilogue.
        # This enables the autotuner to try a Triton kernel for addmm and
        # also supports CV epilogue fusion (e.g. downstream pointwise ops
        # fused into {{store_output}}).
        if is_nonzero and use_triton_template(layout):
            try:
                add_npu_triton_addmm_choices(
                    choices,
                    layout,
                    inp_expanded,
                    mat1,
                    mat2,
                    m,
                    n,
                    k,
                    alpha=alpha,
                    beta=beta,
                )
                log.debug(
                    "NPU Triton CV fusion: added triton addmm template choices "
                    "for addmm(%d, %d, %d), total choices now %d",
                    m,
                    n,
                    k,
                    len(choices),
                )
            except Exception as e:
                log.warning("Failed to add NPU triton addmm template choices: %s", e)

        add_aten_fallback = False
        if len(choices) == 0:
            log.warning("No choices for GEMM, using ATen backend as fallback")
            add_aten_fallback = True

        if add_aten_fallback:
            choices.append(
                aten_addmm.bind(
                    (inp_expanded, mat1, mat2),
                    layout,
                    ordered_kwargs_for_cpp_kernel,
                    alpha=alpha,
                    beta=beta,
                )
            )

        try:
            return autotune_select_algorithm(
                "addmm", choices, [inp_expanded, mat1, mat2], layout
            )
        except NoValidChoicesError:
            if not inductor_config.autotune_fallback_to_aten:
                raise
            log.warning(
                "All choices for GEMM were invalid, using ATen backend as fallback"
            )
            fallback_choice = aten_addmm.bind(
                (inp, mat1, mat2),
                layout,
                ordered_kwargs_for_cpp_kernel,
                alpha=alpha,
                beta=beta,
            )
            return fallback_choice.output_node()
