def is_precision_fallback(op):
    return str(op) in LOWERING_PRECISION_FALLBACK_NAMES


def is_lowering_fallback(op):
    if isinstance(op, torch._ops.HigherOrderOperator):
        return f"higher_order.{op}" in LOWERING_FALLBACK_NAMES
    if isinstance(op, torch._ops.OpOverload):
        if str(op.overloadpacket) in LOWERING_FALLBACK_NAMES:
            return True
    return str(op) in LOWERING_FALLBACK_NAMES
